import uuid
from django.db import models
from django.utils import timezone


class FAQ(models.Model):
    """
    Frequently Asked Questions stored in SQL.
    Minimum of 10 FAQs required by specification.
    """
    CATEGORY_CHOICES = [
        ('general', 'General & Getting Started'),
        ('music', 'Music & Spotify Integration'),
        ('ai', 'Vibe AI & Mood Algorithms'),
        ('system', 'System, Privacy & Security'),
        ('errors', 'Errors & Troubleshooting'),
    ]

    question = models.CharField(max_length=255, help_text="FAQ Question")
    answer = models.TextField(help_text="Detailed Answer")
    category = models.CharField(max_length=50, choices=CATEGORY_CHOICES, default='general')
    order = models.PositiveIntegerField(default=0, help_text="Ordering index for display")
    is_active = models.BooleanField(default=True, help_text="Show in FAQ page")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['order', 'id']
        verbose_name = 'FAQ'
        verbose_name_plural = 'FAQs'

    def __str__(self):
        return f"[{self.get_category_display()}] {self.question}"


class ErrorCode(models.Model):
    """
    HTTP and Custom Error Codes catalog stored in SQL.
    Required minimum of 8 error codes:
    400, 401, 403, 404, 429, 500, 503, and one site-specific code (418 Vibe Mismatch).
    """
    code = models.IntegerField(unique=True, help_text="HTTP or Custom Error Code integer")
    title = models.CharField(max_length=150, help_text="Error title (e.g. Bad Request)")
    category = models.CharField(max_length=50, default="Client Error (4xx)")
    description = models.TextField(help_text="Detailed explanation of what the error means")
    common_causes = models.TextField(help_text="Typical scenarios that trigger this code")
    resolution_steps = models.TextField(help_text="Actionable steps for users and developers to resolve it")
    is_custom = models.BooleanField(default=False, help_text="True if this is a site-specific code")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['code']
        verbose_name = 'Error Code'
        verbose_name_plural = 'Error Codes'

    def __str__(self):
        return f"{self.code} - {self.title}"


class SupportTicket(models.Model):
    """
    Support tickets created in SQL when the AI assistant cannot answer
    or when submitted directly by users.
    """
    STATUS_CHOICES = [
        ('open', 'Open'),
        ('in_progress', 'In Progress'),
        ('resolved', 'Resolved'),
    ]

    PRIORITY_CHOICES = [
        ('low', 'Low'),
        ('medium', 'Medium'),
        ('high', 'High'),
    ]

    ticket_id = models.CharField(max_length=20, unique=True, editable=False)
    user_name = models.CharField(max_length=100, default="Anonymous Listener")
    user_email = models.EmailField(default="listener@vibecheck.io")
    subject = models.CharField(max_length=200)
    message = models.TextField()
    ai_context = models.TextField(blank=True, null=True, help_text="Context of conversation when generated by AI")
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='open')
    priority = models.CharField(max_length=20, choices=PRIORITY_CHOICES, default='medium')
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'Support Ticket'
        verbose_name_plural = 'Support Tickets'

    def save(self, *args, **kwargs):
        if not self.ticket_id:
            # Generate human-friendly ID like TCK-48192
            short_id = uuid.uuid4().hex[:6].upper()
            self.ticket_id = f"TCK-{short_id}"
        super().save(*args, **kwargs)

    def __str__(self):
        return f"[{self.ticket_id}] {self.subject} ({self.get_status_display()})"
